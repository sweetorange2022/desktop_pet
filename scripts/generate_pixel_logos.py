"""生成像素风格 Logo 图片。

生成 4 个像素风格的 logo 到 assets/ico/ 目录：
1. claude_pixel.png - Claude (暖色调猫头)
2. codex_pixel.png  - Codex (代码风格方块)
3. deepseek_pixel.png - DeepSeek (蓝色眼睛)
4. 水屯噜噜_pixel.png - 水屯噜噜 (可爱猪头)
"""

from PIL import Image, ImageDraw

PIXEL = 4  # 每个逻辑像素放大 4 倍
SIZE = 32  # 逻辑像素尺寸（输出 = 32 * 4 = 128px）
OUTPUT_DIR = "assets/ico"


def _upscale(grid: list[list[int]], palette: dict[int, tuple[int, int, int, int]], pixel: int = PIXEL) -> Image.Image:
    """将二维网格按 palette 映射颜色，upscale 输出 RGBA 图像。"""
    h = len(grid)
    w = len(grid[0])
    img = Image.new("RGBA", (w * pixel, h * pixel), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    for y, row in enumerate(grid):
        for x, val in enumerate(row):
            if val not in palette:
                continue
            color = palette[val]
            draw.rectangle(
                [x * pixel, y * pixel, (x + 1) * pixel - 1, (y + 1) * pixel - 1],
                fill=color,
            )
    return img


